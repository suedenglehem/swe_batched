#!/usr/bin/env bash
# Generic batched run against ANY OpenAI-compatible model endpoint.
# Generates the model config on the fly, then runs the shared resumable engine.
#
# Usage: ./run_model.sh <MODEL_NAME> <HOST:PORT> [RUN_ID] [N_TASKS]
#   MODEL_NAME  model id exactly as listed by GET /v1/models (e.g. qwen3.8-flash)
#   HOST:PORT   endpoint location  (e.g. localhost:8080, 192.168.0.33:8080)
#   RUN_ID      results folder name; default: bench-<MODEL_NAME>
#   N_TASKS     number of NEW tasks this session (default 10)
#
# Examples:
#   ./run_model.sh qwen3.8-flash localhost:8080
#   ./run_model.sh swift-1.5-iq3_xxs 192.168.0.33:8080 bench-swift 4
set -euo pipefail

SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)

MODEL="${1:?model name required (as listed by /v1/models)}"
HOSTPORT="${2:?endpoint required, e.g. localhost:8080}"
SLUG="${MODEL//[^a-zA-Z0-9]/-}"
RUN_ID="${3:-bench-$SLUG}"
N="${4:-10}"

mkdir -p "$SCRIPT_DIR/models"
CONFIG="$SCRIPT_DIR/models/gen-$SLUG.yaml"
cat > "$CONFIG" <<EOF
# Generated by run_model.sh at $(date -Iseconds)
model:
  model_name: openai/$MODEL
  cost_tracking: ignore_errors
  model_kwargs:
    api_base: http://$HOSTPORT/v1
    api_key: local-server-not-needed
    drop_params: true
    parallel_tool_calls: true
EOF

echo "model=$MODEL endpoint=http://$HOSTPORT/v1 run_id=$RUN_ID new_tasks=$N"
exec "$SCRIPT_DIR/run_bench.sh" "$CONFIG" "$RUN_ID" "$N"
